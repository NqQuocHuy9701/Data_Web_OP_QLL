create table if not exists public.class_schedule_requests (
  id bigint generated by default as identity primary key,
  ma_lop text not null,
  mon_hoc text not null default '',
  nguoi_tao text not null,
  team text not null default '',
  sid_cid text not null check (sid_cid ~ '^[0-9]{1,8}$'),
  "timestamp" bigint not null,
  created_at timestamptz not null default now()
);

alter table public.class_schedule_requests enable row level security;

grant insert on table public.class_schedule_requests to anon;
grant usage, select on sequence public.class_schedule_requests_id_seq to anon;

create policy "Allow anonymous class schedule request inserts"
  on public.class_schedule_requests
  for insert
  to anon
  with check (true);
